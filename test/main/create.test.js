import { describe, expect, it } from 'vitest';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { buildCreateSql, checkMongoDatabase, checkMongoCollection, checkFirestoreCollection } = require('../../src/main/connectors/create.js');

const table = (dialect, extra = {}) =>
  buildCreateSql(dialect, {
    kind: 'table',
    name: 'users',
    columns: [
      { name: 'id', type: dialect === 'mysql' ? 'int' : 'integer', primaryKey: true, autoIncrement: true },
      { name: 'email', type: 'varchar(255)', nullable: false },
      { name: 'bio', type: 'text', nullable: true }
    ],
    ...extra
  });

describe('buildCreateSql', () => {
  it('creates databases and quotes the name', () => {
    expect(buildCreateSql('postgres', { kind: 'database', name: 'a"b' })).toBe('CREATE DATABASE "a""b"');
    expect(buildCreateSql('mysql', { kind: 'database', name: 'a`b' })).toBe('CREATE DATABASE `a``b`');
  });

  it('creates schemas for PostgreSQL only', () => {
    expect(buildCreateSql('postgres', { kind: 'schema', name: 'sales' })).toBe('CREATE SCHEMA "sales"');
    expect(() => buildCreateSql('mysql', { kind: 'schema', name: 'sales' })).toThrow(/database/);
  });

  it('builds a PostgreSQL table with identity and primary key', () => {
    const sql = table('postgres', { schema: 'public' });
    expect(sql).toContain('CREATE TABLE "public"."users"');
    expect(sql).toContain('"id" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY');
    expect(sql).toContain('"email" varchar(255) NOT NULL');
    expect(sql).toContain('"bio" text,');
    expect(sql).toContain('PRIMARY KEY ("id")');
  });

  it('builds a MySQL table with AUTO_INCREMENT', () => {
    const sql = table('mysql', { schema: 'shop' });
    expect(sql).toContain('CREATE TABLE `shop`.`users`');
    expect(sql).toContain('`id` int NOT NULL AUTO_INCREMENT');
    expect(sql).toContain('PRIMARY KEY (`id`)');
    expect(sql).toContain('`email` varchar(255) NOT NULL');
  });

  it('does not add identity to serial columns', () => {
    const sql = buildCreateSql('postgres', { kind: 'table', name: 't', columns: [{ name: 'id', type: 'serial', primaryKey: true, autoIncrement: true }] });
    expect(sql).not.toContain('IDENTITY');
  });

  it('rejects types that are not on the list, including injected text', () => {
    const column = type => ({ kind: 'table', name: 't', columns: [{ name: 'a', type }] });
    expect(() => buildCreateSql('postgres', column('int); DROP TABLE x; --'))).toThrow(/not a column type/);
    expect(() => buildCreateSql('postgres', column('text primary key'))).toThrow(/not a column type/);
    expect(() => buildCreateSql('mysql', column('text[]'))).toThrow(/PostgreSQL/);
    expect(buildCreateSql('postgres', column('numeric(10, 2)'))).toContain('numeric(10,2)');
  });

  it('rejects empty, duplicate and badly named input', () => {
    expect(() => buildCreateSql('postgres', { kind: 'table', name: 't', columns: [] })).toThrow(/at least one column/);
    expect(() =>
      buildCreateSql('postgres', {
        kind: 'table',
        name: 't',
        columns: [
          { name: 'a', type: 'text' },
          { name: 'A', type: 'text' }
        ]
      })
    ).toThrow(/same name/);
    expect(() => buildCreateSql('postgres', { kind: 'database', name: ' x' })).toThrow();
    expect(() => buildCreateSql('postgres', { kind: 'database', name: 'x'.repeat(64) })).toThrow(/at most/);
    expect(() => buildCreateSql('postgres', { kind: 'database', name: 'a\nb' })).toThrow();
  });

  it('rejects auto-increment on a non-integer column', () => {
    expect(() => buildCreateSql('mysql', { kind: 'table', name: 't', columns: [{ name: 'a', type: 'text', autoIncrement: true }] })).toThrow(/integer/);
  });
});

describe('name checks for document databases', () => {
  it('validates MongoDB names', () => {
    expect(checkMongoDatabase('shop')).toBe('shop');
    expect(() => checkMongoDatabase('my db')).toThrow();
    expect(() => checkMongoDatabase('a.b')).toThrow();
    expect(checkMongoCollection('orders.2024')).toBe('orders.2024');
    expect(() => checkMongoCollection('system.users')).toThrow();
    expect(() => checkMongoCollection('a$b')).toThrow();
  });

  it('validates Firestore collection ids', () => {
    expect(checkFirestoreCollection('users')).toBe('users');
    expect(() => checkFirestoreCollection('a/b')).toThrow();
    expect(() => checkFirestoreCollection('__name__')).toThrow();
    expect(() => checkFirestoreCollection('..')).toThrow();
  });
});

describe('column defaults', () => {
  const withDefault = (dialect, type, defaultValue) => buildCreateSql(dialect, { kind: 'table', name: 't', columns: [{ name: 'a', type, nullable: true, defaultValue }] });

  it('writes numbers, booleans, text and current time as plain values', () => {
    expect(withDefault('postgres', 'integer', '0')).toContain('"a" integer DEFAULT 0');
    expect(withDefault('postgres', 'boolean', 'TRUE')).toContain('DEFAULT TRUE');
    expect(withDefault('mysql', 'varchar(20)', "it's")).toContain("DEFAULT 'it''s'");
    expect(withDefault('mysql', 'varchar(20)', 'a\\b')).toContain("DEFAULT 'a\\\\b'");
    expect(withDefault('postgres', 'timestamptz', 'now()')).toContain('DEFAULT CURRENT_TIMESTAMP');
    expect(withDefault('mysql', 'date', 'current_date')).toContain('DEFAULT CURRENT_DATE');
  });

  it('adds nothing for an empty default', () => {
    expect(withDefault('postgres', 'text', '')).not.toContain('DEFAULT');
    expect(withDefault('postgres', 'text', undefined)).not.toContain('DEFAULT');
  });

  it('rejects defaults that are not plain values', () => {
    expect(() => withDefault('postgres', 'integer', '1); DROP TABLE x; --')).toThrow(/number/);
    expect(() => withDefault('postgres', 'boolean', 'maybe')).toThrow(/true or false/);
    expect(() => withDefault('postgres', 'serial', '1')).toThrow(/serial/);
    expect(() => withDefault('postgres', 'text', 'a\nb')).toThrow(/control/);
    expect(() => buildCreateSql('mysql', { kind: 'table', name: 't', columns: [{ name: 'a', type: 'int', autoIncrement: true, defaultValue: '1' }] })).toThrow(/auto-increment/);
  });

  it('treats now() as text on a column that is not a date or time', () => {
    expect(withDefault('postgres', 'text', 'now()')).toContain("DEFAULT 'now()'");
  });
});

describe('buildAlterSql', () => {
  const { buildAlterSql } = require('../../src/main/connectors/create.js');
  const object = { name: 't', schema: 's' };
  const mysqlCurrent = {
    qty: { type: 'int(11)', nullable: true, defaultValue: null, auto: false },
    id: { type: 'int(11)', nullable: false, defaultValue: null, auto: true },
    created: { type: 'timestamp', nullable: false, defaultValue: 'CURRENT_TIMESTAMP', defaultGenerated: true },
    note: { type: 'varchar(20)', nullable: true, defaultValue: "it's", auto: false }
  };

  it('writes PostgreSQL changes one statement each', () => {
    const sql = buildAlterSql(
      'postgres',
      object,
      [
        { op: 'drop', name: 'old' },
        { op: 'rename', name: 'a', to: 'b' },
        { op: 'modify', name: 'b', type: 'varchar(20)', nullable: false, defaultValue: 'x' },
        { op: 'add', column: { name: 'c', type: 'integer', nullable: true, defaultValue: '3' } },
        { op: 'renameTable', to: 'u' }
      ],
      { b: { type: 'text', nullable: true } }
    );
    expect(sql).toEqual([
      'ALTER TABLE "s"."t" DROP COLUMN "old"',
      'ALTER TABLE "s"."t" RENAME COLUMN "a" TO "b"',
      'ALTER TABLE "s"."t" ALTER COLUMN "b" TYPE varchar(20) USING "b"::varchar(20)',
      'ALTER TABLE "s"."t" ALTER COLUMN "b" SET NOT NULL',
      `ALTER TABLE "s"."t" ALTER COLUMN "b" SET DEFAULT 'x'`,
      'ALTER TABLE "s"."t" ADD COLUMN "c" integer DEFAULT 3',
      'ALTER TABLE "s"."t" RENAME TO "u"'
    ]);
  });

  it('uses the reported type to write a default for an existing PostgreSQL column', () => {
    const current = { n: { type: 'integer', nullable: true }, t: { type: 'character varying(5)', nullable: true } };
    expect(buildAlterSql('postgres', object, [{ op: 'modify', name: 'n', defaultValue: '7' }], current)).toEqual(['ALTER TABLE "s"."t" ALTER COLUMN "n" SET DEFAULT 7']);
    expect(buildAlterSql('postgres', object, [{ op: 'modify', name: 't', defaultValue: 'x' }], current)).toEqual([`ALTER TABLE "s"."t" ALTER COLUMN "t" SET DEFAULT 'x'`]);
    expect(buildAlterSql('postgres', object, [{ op: 'modify', name: 'n', defaultValue: '' }], current)).toEqual(['ALTER TABLE "s"."t" ALTER COLUMN "n" DROP DEFAULT']);
    expect(() => buildAlterSql('postgres', object, [{ op: 'modify', name: 'n', defaultValue: 'abc' }], current)).toThrow(/number/);
  });

  it('only sets or drops the default when that is all that changed in MySQL', () => {
    expect(buildAlterSql('mysql', object, [{ op: 'modify', name: 'qty', defaultValue: '0' }], mysqlCurrent)).toEqual(['ALTER TABLE `s`.`t` ALTER COLUMN `qty` SET DEFAULT 0']);
    expect(buildAlterSql('mysql', object, [{ op: 'modify', name: 'qty', defaultValue: '' }], mysqlCurrent)).toEqual(['ALTER TABLE `s`.`t` ALTER COLUMN `qty` DROP DEFAULT']);
  });

  it('keeps what a MySQL column already has when its type or nullability changes', () => {
    const [qty] = buildAlterSql('mysql', object, [{ op: 'modify', name: 'qty', type: 'bigint' }], mysqlCurrent);
    expect(qty).toBe('ALTER TABLE `s`.`t` MODIFY COLUMN `qty` bigint');
    const [id] = buildAlterSql('mysql', object, [{ op: 'modify', name: 'id', type: 'bigint' }], mysqlCurrent);
    expect(id).toBe('ALTER TABLE `s`.`t` MODIFY COLUMN `id` bigint NOT NULL AUTO_INCREMENT');
    const [created] = buildAlterSql('mysql', object, [{ op: 'modify', name: 'created', nullable: true }], mysqlCurrent);
    expect(created).toBe('ALTER TABLE `s`.`t` MODIFY COLUMN `created` timestamp DEFAULT CURRENT_TIMESTAMP');
    const [note] = buildAlterSql('mysql', object, [{ op: 'modify', name: 'note', nullable: false }], mysqlCurrent);
    expect(note).toBe("ALTER TABLE `s`.`t` MODIFY COLUMN `note` varchar(20) NOT NULL DEFAULT 'it''s'");
  });

  it('refuses unknown columns, bad types and empty changes', () => {
    expect(() => buildAlterSql('mysql', object, [{ op: 'modify', name: 'nope', type: 'int' }], mysqlCurrent)).toThrow(/not found/);
    expect(() => buildAlterSql('postgres', object, [{ op: 'modify', name: 'a', type: 'int); DROP TABLE x' }], { a: { type: 'text' } })).toThrow(/not a column type/);
    expect(() => buildAlterSql('postgres', object, [], {})).toThrow(/no changes/);
    expect(() => buildAlterSql('postgres', object, [{ op: 'rename', name: 'a', to: ' b' }], {})).toThrow();
  });
});
