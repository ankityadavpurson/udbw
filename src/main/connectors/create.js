// Creating databases, schemas, tables and collections. Names are checked and quoted here and column types come from a
// fixed list, so nothing the user typed is ever spliced into the statement as-is.

const MAX_COLUMNS = 200;

const quoteFor = dialect => (dialect === 'mysql' ? value => `\`${String(value).replace(/`/g, '``')}\`` : value => `"${String(value).replace(/"/g, '""')}"`);

// A name is text of 1..max characters without control characters or leading/trailing blanks.
function checkName(value, label, max = 63) {
  const name = typeof value === 'string' ? value : '';
  // eslint-disable-next-line no-control-regex
  if (!name || name !== name.trim() || /[\u0000-\u001f\u007f]/.test(name)) throw new Error(`Enter a ${label} name without leading or trailing spaces.`);
  if (name.length > max) throw new Error(`The ${label} name can have at most ${max} characters.`);
  return name;
}

const SQL_TYPES = {
  postgres: [
    'smallint',
    'integer',
    'bigint',
    'serial',
    'bigserial',
    'numeric',
    'real',
    'double precision',
    'boolean',
    'text',
    'varchar',
    'char',
    'uuid',
    'date',
    'time',
    'timestamp',
    'timestamptz',
    'json',
    'jsonb',
    'bytea'
  ],
  mysql: [
    'tinyint',
    'smallint',
    'int',
    'bigint',
    'decimal',
    'float',
    'double',
    'boolean',
    'varchar',
    'char',
    'text',
    'longtext',
    'json',
    'date',
    'time',
    'datetime',
    'timestamp',
    'blob'
  ]
};
const INTEGER = new Set(['smallint', 'integer', 'bigint', 'int', 'tinyint']);
const SERIAL = new Set(['serial', 'bigserial']);

// "varchar(255)", "numeric(10,2)", "text[]" -> a type from the list above, with an optional size and (PostgreSQL) array suffix.
function checkType(dialect, value) {
  const match = /^([a-z ]+?)\s*(\(\s*\d{1,5}(?:\s*,\s*\d{1,3})?\s*\))?\s*(\[\])?$/.exec(
    String(value || '')
      .trim()
      .toLowerCase()
  );
  const base = match?.[1];
  if (!base || !SQL_TYPES[dialect].includes(base)) throw new Error(`"${value}" is not a column type this database can create here.`);
  if (match[3] && dialect !== 'postgres') throw new Error('Array columns are only available in PostgreSQL.');
  return { base, text: `${base}${match[2] ? match[2].replace(/\s+/g, '') : ''}${match[3] || ''}` };
}

const NUMERIC = new Set(['smallint', 'integer', 'bigint', 'int', 'tinyint', 'numeric', 'decimal', 'real', 'float', 'double', 'double precision']);
const TEMPORAL = { date: 'CURRENT_DATE', time: 'CURRENT_TIME', timestamp: 'CURRENT_TIMESTAMP', timestamptz: 'CURRENT_TIMESTAMP', datetime: 'CURRENT_TIMESTAMP' };

// A default is a plain value, never an expression: a number, true / false, the current date or time for a date or time
// column, or text (quoted here).
function defaultSql(dialect, name, base, value) {
  const raw = typeof value === 'string' ? value : '';
  if (!raw.trim()) return '';
  if (SERIAL.has(base)) throw new Error(`Column ${name}: a serial column numbers itself and cannot have a default.`);
  const lower = raw.trim().toLowerCase();
  if (TEMPORAL[base] && /^(current_(timestamp|date|time)|now\(\))$/.test(lower)) return base === 'date' ? 'CURRENT_DATE' : base === 'time' ? 'CURRENT_TIME' : 'CURRENT_TIMESTAMP';
  if (NUMERIC.has(base)) {
    if (!/^-?\d+(\.\d+)?$/.test(raw.trim())) throw new Error(`Column ${name}: the default must be a number.`);
    return raw.trim();
  }
  if (base === 'boolean') {
    if (!/^(true|false|1|0)$/.test(lower)) throw new Error(`Column ${name}: the default must be true or false.`);
    return lower === 'true' || lower === '1' ? 'TRUE' : 'FALSE';
  }
  const text = dialect === 'mysql' ? raw.replace(/\\/g, '\\\\') : raw;
  // eslint-disable-next-line no-control-regex
  if (/[\u0000-\u001f\u007f]/.test(raw)) throw new Error(`Column ${name}: the default cannot contain control characters.`);
  return `'${text.replace(/'/g, "''")}'`;
}

function columnSql(dialect, quote, column, isKey) {
  const name = checkName(column?.name, 'column', dialect === 'mysql' ? 64 : 63);
  const { base, text } = checkType(dialect, column.type);
  const auto = Boolean(column.autoIncrement) && (INTEGER.has(base) || SERIAL.has(base));
  if (column.autoIncrement && !auto) throw new Error(`Column ${name}: auto-increment needs an integer type.`);
  const parts = [quote(name), text];
  if (!column.nullable || isKey) parts.push('NOT NULL');
  if (auto && !SERIAL.has(base)) parts.push(dialect === 'mysql' ? 'AUTO_INCREMENT' : 'GENERATED BY DEFAULT AS IDENTITY');
  const fallback = defaultSql(dialect, name, base, column.defaultValue);
  if (fallback && auto) throw new Error(`Column ${name}: an auto-increment column cannot have a default.`);
  if (fallback) parts.push(`DEFAULT ${fallback}`);
  return parts.join(' ');
}

// spec: { kind: 'database' | 'schema' | 'table', name, schema?, columns?: [{ name, type, nullable?, primaryKey?, autoIncrement?, defaultValue? }] }
function buildCreateSql(dialect, spec) {
  if (dialect !== 'mysql' && dialect !== 'postgres') throw new Error('Unsupported database type.');
  const quote = quoteFor(dialect);
  const max = dialect === 'mysql' ? 64 : 63;
  if (spec.kind === 'database') return `CREATE DATABASE ${quote(checkName(spec.name, 'database', max))}`;
  if (spec.kind === 'schema') {
    if (dialect !== 'postgres') throw new Error('MySQL has no schemas apart from databases. Create a database instead.');
    return `CREATE SCHEMA ${quote(checkName(spec.name, 'schema', max))}`;
  }
  if (spec.kind !== 'table') throw new Error('This database cannot create that kind of object.');

  const name = checkName(spec.name, 'table', max);
  const columns = Array.isArray(spec.columns) ? spec.columns : [];
  if (!columns.length) throw new Error('Add at least one column.');
  if (columns.length > MAX_COLUMNS) throw new Error(`A table can have at most ${MAX_COLUMNS} columns here.`);
  const names = columns.map(column => String(column?.name ?? '').toLowerCase());
  if (new Set(names).size !== names.length) throw new Error('Two columns have the same name.');
  const lines = columns.map(column => columnSql(dialect, quote, column, Boolean(column.primaryKey)));
  const keys = columns.filter(column => column.primaryKey).map(column => quote(column.name));
  if (keys.length) lines.push(`PRIMARY KEY (${keys.join(', ')})`);
  const schema = spec.schema ? `${quote(checkName(spec.schema, 'schema', max))}.` : '';
  return `CREATE TABLE ${schema}${quote(name)} (\n  ${lines.join(',\n  ')}\n)`;
}

// The family of a type as the database reports it ("character varying(255)", "int unsigned", "timestamp with time zone"),
// in the names used by SQL_TYPES, so a default can be written for an existing column too.
const REPORTED = {
  'character varying': 'varchar',
  character: 'char',
  'timestamp without time zone': 'timestamp',
  'timestamp with time zone': 'timestamptz',
  'time without time zone': 'time',
  'time with time zone': 'time'
};
function baseOf(type) {
  const base = String(type || '')
    .toLowerCase()
    .replace(/\(.*?\)/g, '')
    .replace(/\[\]$/, '')
    .replace(/\b(unsigned|signed|zerofill)\b/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return REPORTED[base] || base;
}

// What a column already has as its default, written back unchanged (the database itself reported it).
function keptDefault(current) {
  if (current.defaultValue === null || current.defaultValue === undefined) return '';
  const raw = String(current.defaultValue);
  if (current.defaultGenerated) return raw;
  return NUMERIC.has(baseOf(current.type)) && /^-?\d+(\.\d+)?$/.test(raw) ? raw : `'${raw.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
}

// ops: [{ op: 'drop', name } | { op: 'rename', name, to } | { op: 'modify', name, type?, nullable?, defaultValue? } |
//       { op: 'add', column } | { op: 'renameTable', to }]. In a modify, a field left out is not changed and an empty
// defaultValue removes the default. `current` is what describe() reported for each existing column, by name.
// Returns the statements to run, in order.
function buildAlterSql(dialect, object, ops, current = {}) {
  if (dialect !== 'mysql' && dialect !== 'postgres') throw new Error('Unsupported database type.');
  if (!Array.isArray(ops) || !ops.length) throw new Error('There are no changes to apply.');
  const quote = quoteFor(dialect);
  const max = dialect === 'mysql' ? 64 : 63;
  const schema = object?.schema ? `${quote(checkName(object.schema, 'schema', max))}.` : '';
  const alter = clause => `ALTER TABLE ${schema}${quote(checkName(object?.name, 'table', max))} ${clause}`;
  const columnName = value => checkName(value, 'column', max);
  const known = name => {
    const column = current[name];
    if (!column) throw new Error(`Column ${name} was not found in the table.`);
    return column;
  };
  const statements = [];

  for (const op of ops) {
    if (op.op === 'drop') statements.push(alter(`DROP COLUMN ${quote(columnName(op.name))}`));
    else if (op.op === 'rename') statements.push(alter(`RENAME COLUMN ${quote(columnName(op.name))} TO ${quote(columnName(op.to))}`));
    else if (op.op === 'renameTable') statements.push(alter(`RENAME TO ${quote(checkName(op.to, 'table', max))}`));
    else if (op.op === 'add') statements.push(alter(`ADD COLUMN ${columnSql(dialect, quote, { ...op.column, primaryKey: false }, false)}`));
    else if (op.op === 'modify') {
      const name = columnName(op.name);
      const column = known(name);
      const col = quote(name);
      const type = op.type === undefined ? null : checkType(dialect, op.type);
      const base = type ? type.base : baseOf(column.type);
      const fallback = op.defaultValue === undefined ? undefined : defaultSql(dialect, name, base, op.defaultValue);
      if (dialect === 'postgres') {
        if (type) statements.push(alter(`ALTER COLUMN ${col} TYPE ${type.text} USING ${col}::${type.text}`));
        if (op.nullable !== undefined) statements.push(alter(`ALTER COLUMN ${col} ${op.nullable ? 'DROP' : 'SET'} NOT NULL`));
        if (fallback !== undefined) statements.push(alter(`ALTER COLUMN ${col} ${fallback ? `SET DEFAULT ${fallback}` : 'DROP DEFAULT'}`));
      } else if (!type && op.nullable === undefined) {
        if (fallback !== undefined) statements.push(alter(`ALTER COLUMN ${col} ${fallback ? `SET DEFAULT ${fallback}` : 'DROP DEFAULT'}`));
      } else {
        if (column.generated) throw new Error(`Column ${name} is a generated column and cannot be changed here.`);
        const kept = fallback === undefined ? keptDefault(column) : fallback;
        const nullable = op.nullable === undefined ? column.nullable : op.nullable;
        statements.push(
          alter(`MODIFY COLUMN ${col} ${type ? type.text : column.type}${nullable ? '' : ' NOT NULL'}${kept ? ` DEFAULT ${kept}` : ''}${column.auto ? ' AUTO_INCREMENT' : ''}`)
        );
      }
    } else throw new Error('Unsupported change.');
  }
  return statements;
}

// MongoDB: a database name cannot hold / \ . " $ * < > : | ? or spaces; a collection name cannot be empty, hold $ or start with "system.".
function checkMongoDatabase(value) {
  const name = checkName(value, 'database', 63);
  if (/[/\\. "$*<>:|?]/.test(name)) throw new Error('A database name cannot contain spaces or any of / \\ . " $ * < > : | ?');
  return name;
}
function checkMongoCollection(value) {
  const name = checkName(value, 'collection', 120);
  if (name.includes('$') || name.startsWith('system.')) throw new Error('A collection name cannot contain $ or start with "system.".');
  return name;
}

// Firestore: a collection id has no "/", is not "." or "..", and does not look like __name__.
function checkFirestoreCollection(value) {
  const name = checkName(value, 'collection', 1500);
  if (name.includes('/') || name === '.' || name === '..' || /^__.*__$/.test(name)) throw new Error('A collection name cannot contain "/", be "." or "..", or look like __name__.');
  return name;
}

module.exports = { buildAlterSql, buildCreateSql, checkMongoDatabase, checkMongoCollection, checkFirestoreCollection, SQL_TYPES };
